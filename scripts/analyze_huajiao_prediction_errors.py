#!/usr/bin/env python3
"""Analyze per-sample prediction errors by sheet/batch and generate plots.

This script works with outputs generated by `scripts/train_huajiao_oil_content.py`,
especially `predictions_all.csv` under a `results/...` directory.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, Optional, Sequence

import numpy as np
import pandas as pd

# Ensure local src is importable when running directly.
repo_root = Path(__file__).resolve().parent.parent
src_path = repo_root / "src"
if src_path.exists():
    sys.path.insert(0, str(src_path))

from oil_content_detection.acquisition import load_envi_cube  # noqa: E402


def normalize_sample_id(raw: str) -> str:
    cleaned = str(raw).strip()
    cleaned = cleaned.replace("-", "_").replace("—", "_").replace("－", "_")
    cleaned = re.sub(r"[^0-9A-Za-z_]+", "_", cleaned)
    cleaned = re.sub(r"_+", "_", cleaned).strip("_")
    return cleaned


def _read_df(path: Path) -> pd.DataFrame:
    if path.exists():
        return pd.read_parquet(path) if path.suffix.lower() == ".parquet" else pd.read_csv(path)
    csv_path = path.with_suffix(".csv")
    if csv_path.exists():
        return pd.read_csv(csv_path)
    raise FileNotFoundError(f"File not found: {path} (or {csv_path})")


def _setup_matplotlib() -> None:
    try:
        import matplotlib as mpl
    except Exception:
        return

    # Prefer a CJK-capable font (available on this machine).
    mpl.rcParams["font.sans-serif"] = [
        "Noto Sans CJK JP",
        "Noto Sans CJK SC",
        "DejaVu Sans",
        "Arial",
    ]
    mpl.rcParams["axes.unicode_minus"] = False


@dataclass(frozen=True)
class PredictionColumns:
    target_true: str
    target_pred: str


def _detect_target_columns(df: pd.DataFrame) -> PredictionColumns:
    true_cols = [c for c in df.columns if c.endswith("_true")]
    pred_cols = [c for c in df.columns if c.endswith("_pred")]
    if not true_cols or not pred_cols:
        raise ValueError("Cannot find '*_true' and '*_pred' columns in predictions table")

    # Prefer oil_ml_per_100g if present; otherwise pick the first pair.
    preferred_true = "oil_ml_per_100g_true"
    preferred_pred = "oil_ml_per_100g_pred"
    if preferred_true in df.columns and preferred_pred in df.columns:
        return PredictionColumns(target_true=preferred_true, target_pred=preferred_pred)

    # Fallback: match by shared prefix.
    pred_by_prefix: Dict[str, str] = {c[: -len("_pred")]: c for c in pred_cols}
    for tcol in true_cols:
        prefix = tcol[: -len("_true")]
        if prefix in pred_by_prefix:
            return PredictionColumns(target_true=tcol, target_pred=pred_by_prefix[prefix])
    return PredictionColumns(target_true=true_cols[0], target_pred=pred_cols[0])


def _load_sheet_mapping(excel_path: Path) -> pd.DataFrame:
    xls = pd.ExcelFile(excel_path)
    exclude = {"总样品情况", "Sheet3"}
    rows: list[pd.DataFrame] = []
    for sheet in xls.sheet_names:
        if sheet in exclude:
            continue
        df = pd.read_excel(excel_path, sheet_name=sheet)
        if "高光谱图件编号" not in df.columns:
            continue
        sub = df[["高光谱图件编号"]].dropna().copy()
        sub["sample_id"] = sub["高光谱图件编号"].map(normalize_sample_id)
        sub["sheet"] = sheet
        rows.append(sub[["sample_id", "sheet"]])
    if not rows:
        raise ValueError(f"No usable sheets found in {excel_path}")
    return pd.concat(rows, ignore_index=True).drop_duplicates("sample_id", keep="first")


def _mask_area_stats(
    sample_ids: Sequence[str],
    *,
    manual_mask_dir: Path,
    refined_mask_dir: Path,
) -> pd.DataFrame:
    try:
        from PIL import Image
    except Exception as exc:
        raise ImportError("Pillow is required to compute mask area statistics") from exc

    rows = []
    for sid in sample_ids:
        manual_path = manual_mask_dir / f"{sid}_mask.png"
        refined_path = refined_mask_dir / f"{sid}_mask.png"
        if not manual_path.exists() or not refined_path.exists():
            continue

        manual = np.asarray(Image.open(manual_path).convert("L")) > 0
        refined = np.asarray(Image.open(refined_path).convert("L")) > 0
        manual_area = int(manual.sum())
        refined_area = int(refined.sum())
        manual_minus_refined = int((manual & (~refined)).sum())

        removed_ratio = manual_minus_refined / manual_area if manual_area else np.nan
        fill_ratio = refined_area / manual_area if manual_area else np.nan
        rows.append(
            {
                "sample_id": sid,
                "manual_area": manual_area,
                "refined_area": refined_area,
                "manual_minus_refined": manual_minus_refined,
                "manual_minus_refined_ratio": removed_ratio,
                "refined_fill_ratio": fill_ratio,
            }
        )
    return pd.DataFrame(rows)


def _cube_qc_for_samples(
    df: pd.DataFrame,
    *,
    hdr_col: str = "hdr_path",
    refined_mask_dir: Path,
    sample_size: int = 5000,
    seed: int = 2026,
) -> pd.DataFrame:
    """Compute lightweight QC metrics directly from cubes within refined ROI."""
    try:
        from PIL import Image
    except Exception as exc:
        raise ImportError("Pillow is required for cube-QC") from exc

    rng = np.random.default_rng(seed)
    rows = []

    for _, row in df.iterrows():
        sample_id = str(row["sample_id"])
        hdr_path = Path(str(row[hdr_col]))
        mask_path = refined_mask_dir / f"{sample_id}_mask.png"
        if not hdr_path.exists() or not mask_path.exists():
            continue

        cube, _ = load_envi_cube(hdr_path)
        img = Image.open(mask_path).convert("L")
        mask = (np.asarray(img) > 0)
        if mask.shape != (cube.shape[0], cube.shape[1]):
            img_resized = img.resize((cube.shape[1], cube.shape[0]), resample=Image.NEAREST)
            mask = (np.asarray(img_resized) > 0)

        flat_mask = mask.reshape(-1)
        indices = np.flatnonzero(flat_mask)
        if indices.size < 3:
            continue

        take = int(min(sample_size, indices.size))
        chosen = rng.choice(indices, size=take, replace=False)

        flat_cube = cube.reshape(-1, cube.shape[2])
        spectra = flat_cube[chosen].astype(np.float32, copy=False)

        rows.append(
            {
                "sample_id": sample_id,
                "cube_qc_sample_n": int(take),
                "cube_qc_sat_65535_ratio": float((spectra >= 65535).mean()),
                "cube_qc_sat_65000_ratio": float((spectra >= 65000).mean()),
                "cube_qc_zero_ratio": float((spectra <= 0).mean()),
                "cube_qc_mean": float(spectra.mean()),
                "cube_qc_std": float(spectra.std()),
            }
        )
    return pd.DataFrame(rows)


def _compute_spectra_stats(df: pd.DataFrame, *, wl_prefix: str = "wl_") -> pd.DataFrame:
    wl_cols = [c for c in df.columns if c.startswith(wl_prefix)]
    if not wl_cols:
        return pd.DataFrame({"sample_id": df["sample_id"].astype(str)})

    X = df[wl_cols].to_numpy(dtype=float)
    return pd.DataFrame(
        {
            "sample_id": df["sample_id"].astype(str),
            "spectra_wl_mean": np.mean(X, axis=1),
            "spectra_wl_std": np.std(X, axis=1),
            "spectra_wl_min": np.min(X, axis=1),
            "spectra_wl_max": np.max(X, axis=1),
            "spectra_sat_wl_ratio_65000": (X >= 65000).mean(axis=1),
        }
    )


def _save_table(df: pd.DataFrame, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Analyze huajiao prediction errors by sheet/batch")
    parser.add_argument(
        "--predictions",
        type=Path,
        default=Path("results/huajiao_refined_oil_content_20260104_raw/predictions_all.csv"),
        help="Path to predictions_all.csv",
    )
    parser.add_argument(
        "--train-metadata",
        type=Path,
        default=Path("data/processed/huajiao_refined/train/huajiao_metadata.parquet"),
        help="Train metadata parquet (or CSV fallback)",
    )
    parser.add_argument(
        "--val-metadata",
        type=Path,
        default=Path("data/processed/huajiao_refined/val/huajiao_metadata.parquet"),
        help="Val metadata parquet (or CSV fallback)",
    )
    parser.add_argument(
        "--train-spectra",
        type=Path,
        default=Path("data/processed/huajiao_refined/train/huajiao_spectra.parquet"),
        help="Train spectra parquet (or CSV fallback)",
    )
    parser.add_argument(
        "--val-spectra",
        type=Path,
        default=Path("data/processed/huajiao_refined/val/huajiao_spectra.parquet"),
        help="Val spectra parquet (or CSV fallback)",
    )
    parser.add_argument(
        "--excel",
        type=Path,
        default=Path("docs/2025年8月+花椒挥发油测定结果（初步）.xls"),
        help="Label Excel used to map sample_id -> sheet (variety)",
    )
    parser.add_argument(
        "--manual-mask-dir",
        type=Path,
        default=Path("data/processed/ROI_masks_manual"),
        help="Directory of manual contour masks",
    )
    parser.add_argument(
        "--refined-mask-dir",
        type=Path,
        default=Path("data/processed/ROI_masks_refined"),
        help="Directory of refined pepper masks",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results/huajiao_refined_oil_content_20260104_raw/error_analysis"),
        help="Directory to save analysis CSVs and figures",
    )
    parser.add_argument(
        "--cube-qc",
        action="store_true",
        help="Compute extra QC metrics by sampling raw cubes within refined ROI (validation split only)",
    )
    parser.add_argument("--cube-qc-sample-size", type=int, default=5000, help="Pixels per sample for cube-QC")
    parser.add_argument("--seed", type=int, default=2026, help="Random seed for quantiles/QC sampling")
    parser.add_argument("--top-k", type=int, default=10, help="Top-K worst/best samples to export")
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    pred = _read_df(args.predictions)
    cols = _detect_target_columns(pred)

    if "split" not in pred.columns:
        raise KeyError("predictions file must contain a 'split' column (train/val)")
    if "sample_id" not in pred.columns:
        raise KeyError("predictions file must contain a 'sample_id' column")

    # Load metadata to get sample_dir/hdr_path for batch/QC.
    train_meta = _read_df(args.train_metadata)
    val_meta = _read_df(args.val_metadata)
    train_meta["split"] = "train"
    val_meta["split"] = "val"
    meta = pd.concat([train_meta, val_meta], ignore_index=True)

    merged = pred.merge(
        meta[["sample_id", "split", "sample_dir", "hdr_path"]],
        on=["sample_id", "split"],
        how="left",
    )
    merged["batch"] = merged["sample_dir"].apply(
        lambda p: Path(p).parent.name if isinstance(p, str) and p else ""
    )

    # Map to sheet (variety) from Excel.
    sheet_map = _load_sheet_mapping(args.excel)
    merged = merged.merge(sheet_map, on="sample_id", how="left")

    # Spectra-level stats (aggregated wl_).
    train_spec = _read_df(args.train_spectra)
    val_spec = _read_df(args.val_spectra)
    train_spec["split"] = "train"
    val_spec["split"] = "val"
    spec = pd.concat([train_spec, val_spec], ignore_index=True)
    spec_stats = _compute_spectra_stats(spec)
    spec_stats["split"] = spec["split"].astype(str).to_numpy()

    merged = merged.merge(spec_stats, on=["sample_id", "split"], how="left")

    # Mask area stats (manual vs refined).
    mask_stats = _mask_area_stats(
        merged["sample_id"].astype(str).unique().tolist(),
        manual_mask_dir=args.manual_mask_dir,
        refined_mask_dir=args.refined_mask_dir,
    )
    merged = merged.merge(mask_stats, on="sample_id", how="left")

    # Optional cube-based QC for validation only.
    if args.cube_qc:
        val_for_qc = merged[merged["split"] == "val"].copy()
        qc = _cube_qc_for_samples(
            val_for_qc,
            refined_mask_dir=args.refined_mask_dir,
            sample_size=int(args.cube_qc_sample_size),
            seed=int(args.seed),
        )
        merged = merged.merge(qc, on="sample_id", how="left")

    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    # ---- Validation-focused analyses ----
    val = merged[merged["split"] == "val"].copy()
    val = val.dropna(subset=[cols.target_true, cols.target_pred, "abs_error"])

    # Quartiles by abs_error on val.
    val["abs_error_quartile"] = pd.qcut(
        val["abs_error"],
        q=4,
        labels=["best_q1", "q2", "q3", "worst_q4"],
    )

    # Summary by sheet (variety).
    summary_sheet = (
        val.groupby("sheet")
        .agg(
            n=("sample_id", "count"),
            mean_abs_error=("abs_error", "mean"),
            median_abs_error=("abs_error", "median"),
            mean_abs_rel=("abs_relative_error_percent", "mean"),
            mean_error=("error", "mean"),
            median_error=("error", "median"),
        )
        .reset_index()
        .sort_values("mean_abs_error", ascending=False)
    )
    quartile_counts = pd.crosstab(val["sheet"], val["abs_error_quartile"]).reset_index()
    summary_sheet = summary_sheet.merge(quartile_counts, on="sheet", how="left")

    _save_table(summary_sheet, out_dir / "val_summary_by_sheet.csv")

    # Summary by batch (directory).
    summary_batch = (
        val.groupby(["sheet", "batch"])
        .agg(
            n=("sample_id", "count"),
            mean_abs_error=("abs_error", "mean"),
            median_abs_error=("abs_error", "median"),
            mean_abs_rel=("abs_relative_error_percent", "mean"),
            mean_error=("error", "mean"),
        )
        .reset_index()
        .sort_values(["mean_abs_error", "n"], ascending=[False, False])
    )
    _save_table(summary_batch, out_dir / "val_summary_by_batch.csv")

    # Top-K best/worst samples.
    top_k = int(max(1, args.top_k))
    worst_val = val.sort_values("abs_error", ascending=False).head(top_k)
    best_val = val.sort_values("abs_error", ascending=True).head(top_k)
    _save_table(worst_val, out_dir / "val_worst_samples.csv")
    _save_table(best_val, out_dir / "val_best_samples.csv")

    # Group comparison: best_q1 vs worst_q4.
    compare_cols = [
        cols.target_true,
        cols.target_pred,
        "abs_error",
        "abs_relative_error_percent",
        "pixel_count",
        "valid_pixel_count",
        "coverage_ratio",
        "spectra_sat_wl_ratio_65000",
        "spectra_wl_mean",
        "spectra_wl_std",
        "manual_area",
        "refined_area",
        "refined_fill_ratio",
    ]
    if args.cube_qc:
        compare_cols.extend(
            [
                "cube_qc_sat_65535_ratio",
                "cube_qc_sat_65000_ratio",
                "cube_qc_zero_ratio",
                "cube_qc_mean",
                "cube_qc_std",
            ]
        )

    group_stats = (
        val.groupby("abs_error_quartile")[compare_cols]
        .agg(["count", "mean", "median", "std", "min", "max"])
        .reset_index()
    )
    _save_table(group_stats, out_dir / "val_group_stats_quartiles.csv")

    # ---- Plots ----
    try:
        import matplotlib.pyplot as plt
        import seaborn as sns
    except Exception:
        print("Matplotlib/Seaborn unavailable; skipping plots.")
        return

    sns.set_style("whitegrid")
    _setup_matplotlib()

    # Plot 1: abs_error distribution by sheet (boxplot).
    fig = plt.figure(figsize=(12, 5))
    ax = sns.boxplot(
        data=val.sort_values("sheet"),
        x="sheet",
        y="abs_error",
        color="#8fbcd4",
    )
    ax.set_title("验证集：按品种(sheet)的绝对误差分布", fontsize=12)
    ax.set_xlabel("品种(sheet)")
    ax.set_ylabel("abs_error (ml/100g)")
    ax.tick_params(axis="x", rotation=30)
    fig.tight_layout()
    fig.savefig(out_dir / "val_abs_error_by_sheet_boxplot.png", dpi=200)
    plt.close(fig)

    # Plot 2: mean signed error by sheet (bias).
    fig = plt.figure(figsize=(12, 5))
    sheet_bias = (
        val.groupby("sheet")
        .agg(n=("sample_id", "count"), mean_error=("error", "mean"))
        .reset_index()
        .sort_values("mean_error")
    )
    ax = sns.barplot(data=sheet_bias, x="sheet", y="mean_error", color="#d4a08f")
    ax.axhline(0, color="black", linewidth=1.0)
    ax.set_title("验证集：按品种(sheet)的平均偏差（pred-true）", fontsize=12)
    ax.set_xlabel("品种(sheet)")
    ax.set_ylabel("mean(error) (ml/100g)")
    ax.tick_params(axis="x", rotation=30)
    for i, row in enumerate(sheet_bias.itertuples(index=False)):
        ax.text(i, row.mean_error, f"n={row.n}", ha="center", va="bottom", fontsize=9, rotation=0)
    fig.tight_layout()
    fig.savefig(out_dir / "val_mean_error_by_sheet_bar.png", dpi=200)
    plt.close(fig)

    # Plot 3: best/worst quartile counts by sheet.
    fig = plt.figure(figsize=(12, 5))
    ct = pd.crosstab(val["sheet"], val["abs_error_quartile"]).reindex(columns=["best_q1", "worst_q4"], fill_value=0)
    ct = ct.sort_values("worst_q4", ascending=False)
    ax = ct.plot(kind="bar", stacked=True, figsize=(12, 5), color=["#6abf69", "#e06c75"])
    ax.set_title("验证集：各品种的最好/最差四分位样本数", fontsize=12)
    ax.set_xlabel("品种(sheet)")
    ax.set_ylabel("样本数")
    ax.tick_params(axis="x", rotation=30)
    fig = ax.get_figure()
    fig.tight_layout()
    fig.savefig(out_dir / "val_best_worst_quartile_by_sheet_stacked.png", dpi=200)
    plt.close(fig)

    # Plot 4: y_true vs y_pred scatter (colored by sheet).
    fig = plt.figure(figsize=(6, 6))
    ax = sns.scatterplot(
        data=val,
        x=cols.target_true,
        y=cols.target_pred,
        hue="sheet",
        palette="tab10",
        s=55,
        alpha=0.9,
    )
    min_v = float(min(val[cols.target_true].min(), val[cols.target_pred].min()))
    max_v = float(max(val[cols.target_true].max(), val[cols.target_pred].max()))
    ax.plot([min_v, max_v], [min_v, max_v], linestyle="--", color="black", linewidth=1)
    ax.set_title("验证集：真实值 vs 预测值（按品种着色）", fontsize=12)
    ax.set_xlabel(f"{cols.target_true} (ml/100g)")
    ax.set_ylabel(f"{cols.target_pred} (ml/100g)")
    ax.legend(bbox_to_anchor=(1.02, 1), loc="upper left", borderaxespad=0.0, fontsize=9, title="sheet")
    fig.tight_layout()
    fig.savefig(out_dir / "val_true_vs_pred_scatter_by_sheet.png", dpi=220, bbox_inches="tight")
    plt.close(fig)

    print(f"Saved analysis tables/plots to: {out_dir}")


if __name__ == "__main__":
    main()
